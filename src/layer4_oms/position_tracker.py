"""
Position & PnL Accounting Tracker.
Tracks active inventory, weighted average entry prices, realized/unrealized PnL, and fees.
"""

from __future__ import annotations

import logging

from src.core.models import FillEvent, OrderSide, Position

logger = logging.getLogger("multiquant.oms.position_tracker")


class PositionTracker:
    """Maintains active positions and calculates accurate portfolio PnL accounting."""

    def __init__(self) -> None:
        self._positions: dict[str, Position] = {}
        self.total_fees_paid: float = 0.0
        self.total_realized_pnl: float = 0.0

    def get_position(self, symbol: str) -> Position:
        """Get or initialize position for symbol."""
        sym = symbol.upper()
        if sym not in self._positions:
            self._positions[sym] = Position(symbol=sym)
        return self._positions[sym]

    def get_all_positions(self) -> dict[str, Position]:
        """Return dict of all tracked positions."""
        return self._positions.copy()

    def update_mark_price(self, symbol: str, price: float) -> None:
        """Update current market price for unrealized PnL calculation."""
        pos = self.get_position(symbol)
        pos.current_price = price

    def process_fill(self, fill: FillEvent) -> float:
        """
        Updates position based on execution receipt (FillEvent).
        Returns the incremental realized PnL generated by this fill (if any).
        """
        pos = self.get_position(fill.symbol)
        pos.current_price = fill.filled_price
        self.total_fees_paid += fill.fee

        fill_qty = fill.filled_quantity if fill.side == OrderSide.BUY else -fill.filled_quantity
        incremental_realized_pnl = 0.0

        # Scenario 1: Position is currently flat (0.0) -> Open new position
        if not pos.is_open:
            pos.quantity = fill_qty
            pos.entry_price = fill.filled_price
            logger.info(
                "Opened new %s position: %.6f %s @ $%.2f",
                pos.side,
                pos.quantity,
                pos.symbol,
                pos.entry_price,
            )

        # Scenario 2: Adding in same direction (e.g. Long adding to Long)
        elif (pos.quantity > 0 and fill_qty > 0) or (pos.quantity < 0 and fill_qty < 0):
            total_cost = (pos.quantity * pos.entry_price) + (fill_qty * fill.filled_price)
            pos.quantity += fill_qty
            pos.entry_price = total_cost / pos.quantity
            logger.info(
                "Scaled into %s: new size %.6f @ avg $%.2f",
                pos.symbol,
                pos.quantity,
                pos.entry_price,
            )

        # Scenario 3: Closing or reducing existing position (Opposite side)
        else:
            close_qty = min(abs(pos.quantity), abs(fill_qty))
            if pos.quantity > 0:
                # Closing Long (Sold at fill price, bought at entry price)
                incremental_realized_pnl = (
                    fill.filled_price - pos.entry_price
                ) * close_qty - fill.fee
            else:
                # Closing Short (Bought at fill price, shorted at entry price)
                incremental_realized_pnl = (
                    pos.entry_price - fill.filled_price
                ) * close_qty - fill.fee

            pos.realized_pnl += incremental_realized_pnl
            self.total_realized_pnl += incremental_realized_pnl
            pos.quantity += fill_qty  # Net quantity

            # If flipped from Long to Short or Short to Long
            if (fill_qty > 0 and pos.quantity > 0) or (fill_qty < 0 and pos.quantity < 0):
                pos.entry_price = fill.filled_price

            logger.info(
                "Reduced/Closed %s: realized PnL = $%.2f (net quantity: %.6f)",
                pos.symbol,
                incremental_realized_pnl,
                pos.quantity,
            )

        return incremental_realized_pnl
